// writeTree writes files (repo-relative path → content) under a temp root.
func writeTree(t *testing.T, files map[string]string) string {
	t.Helper()
	root := t.TempDir()
	for p, body := range files {
		full := filepath.Join(root, filepath.FromSlash(p))
		if err := os.MkdirAll(filepath.Dir(full), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(full, []byte(body), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	return root
}

func byName(out output, name string) (node, bool) {
	for _, n := range out.Nodes {
		if n.Name == name {
			return n, true
		}
	}
	return node{}, false
}

// Each row: a file's head and whether its functions are marked generated.
func TestGeneratedCases(t *testing.T) {
	cases := []struct {
		name, description, src string
		want                   bool
	}{
		{"positive_protoc", "protoc-gen-go's header",
			"// Code generated by protoc-gen-go. DO NOT EDIT.\n// versions: x\n\npackage p\n\nfunc F() {}\n", true},
		{"positive_after_license", "the marker below a license block, still before package",
			"// Copyright x\n\n// Code generated by stringer; DO NOT EDIT.\n\npackage p\n\nfunc F() {}\n", true},
		{"negative_hand_written", "an ordinary file", "package p\n\nfunc F() {}\n", false},
		{"negative_after_package", "the marker after the package clause does not count",
			"package p\n\n// Code generated by x. DO NOT EDIT.\nfunc F() {}\n", false},
		{"corner_block_comment", "the convention is a line comment, not a block",
			"/* Code generated by x. DO NOT EDIT. */\npackage p\n\nfunc F() {}\n", false},
		{"boundary_missing_period", "the line must end with `DO NOT EDIT.`",
			"// Code generated by x. DO NOT EDIT\npackage p\n\nfunc F() {}\n", false},
		{"adversarial_marker_in_string", "a marker inside a string literal is not a comment",
			"package p\n\nvar s = \"// Code generated by x. DO NOT EDIT.\"\n\nfunc F() {}\n", false},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			root := writeTree(t, map[string]string{"p/f.go": c.src})
			n, ok := byName(analyze(root, nil, maxNodes, maxEdges), "F")
			if !ok {
				t.Fatalf("%s: F not found", c.description)
			}
			if n.Generated != c.want {
				t.Errorf("%s: generated = %v, want %v", c.description, n.Generated, c.want)
			}
		})
	}
}

// Each row: a function and the (line, end_line, test) recorded for it.
func TestNodeFieldCases(t *testing.T) {
	root := writeTree(t, map[string]string{
		"a/a.go":      "package a\n\nfunc One() {}\n\nfunc Three() int {\n\tx := 1\n\treturn x\n}\n",
		"a/a_test.go": "package a\n\nfunc TestOne() {\n\tOne()\n}\n",
		"a/l.go":      "package a\n\n//line other.go:900\nfunc Moved() {\n}\n",
	})
	out := analyze(root, nil, maxNodes, maxEdges)
	cases := []struct {
		name, description, fn string
		line, end             int
		test                  bool
	}{
		{"positive_one_line", "a one-line function ends where it starts", "One", 3, 3, false},
		{"positive_multi_line", "a function's last line is its closing brace", "Three", 5, 8, false},
		{"corner_test_file", "a _test.go function is marked test", "TestOne", 3, 5, true},
		{"adversarial_line_directive", "a //line directive does not move the physical lines", "Moved", 4, 5, false},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			n, ok := byName(out, c.fn)
			if !ok {
				t.Fatalf("%s: %s not found", c.description, c.fn)
			}
			if n.Line != c.line || n.EndLine != c.end || n.Test != c.test {
				t.Errorf("%s: got (%d, %d, %v), want (%d, %d, %v)", c.description, n.Line, n.EndLine, n.Test, c.line, c.end, c.test)
			}
		})
	}
}

// The focus list. Each row: the raw value and the paths kept.
func TestParseFocusCases(t *testing.T) {
	cases := []struct {
		name, description, raw string
		want                   []string
	}{
		{"positive_list", "two paths", "a/a.go\nb/b.go\n", []string{"a/a.go", "b/b.go"}},
		{"corner_cleaned", "a ./ prefix and blank lines are cleaned", "./a/a.go\n\n  \n", []string{"a/a.go"}},
		{"negative_empty", "no focus", "", nil},
		{"adversarial_absolute", "an absolute path is dropped", "/etc/passwd\n", nil},
		{"adversarial_traversal", "a path that climbs out is dropped", "../x.go\na/../../y.go\n", nil},
		{"boundary_inner_dotdot", "a .. that stays inside is cleaned, not dropped", "a/../b.go\n", []string{"b.go"}},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			got := parseFocus(c.raw)
			if len(got) != len(c.want) {
				t.Fatalf("%s: got %v, want %v", c.description, got, c.want)
			}
			for _, w := range c.want {
				if !got[w] {
					t.Errorf("%s: %q missing from %v", c.description, w, got)
				}
			}
		})
	}
}

// A huge focus value is read only up to its caps.
func TestParseFocusIsBounded(t *testing.T) {
	var b strings.Builder
	for i := 0; i < maxFocusPaths*2; i++ {
		b.WriteString("p/")
		b.WriteString(strings.Repeat("x", 10))
		b.WriteString(string(rune('a' + i%26)))
		b.WriteString(strings.Repeat("y", i%50))
		b.WriteString(".go\n")
	}
	if got := len(parseFocus(b.String())); got > maxFocusPaths {
		t.Errorf("kept %d paths, cap %d", got, maxFocusPaths)
	}
}

// A repo bigger than the caps: with focus, the changed function and its caller
// survive the node cap and their edge survives the edge cap; without focus (the
// old walk order) they don't. Each row: whether focus is given, the caps, and
// whether Caller→Target is in the output.
func TestFocusUnderCapsCases(t *testing.T) {
	files := map[string]string{
		// Walked first: many functions that call each other, filling both caps.
		"a/noise.go": "package a\n\nfunc N1() { N2(); N3() }\nfunc N2() { N1(); N3() }\nfunc N3() { N1(); N2() }\nfunc N4() { N1() }\n",
		// Walked last: the change and its caller.
		"z/target.go": "package z\n\nfunc Target() int { return 1 }\n",
		"z/caller.go": "package z\n\nfunc Caller() int { return Target() }\n",
	}
	root := writeTree(t, files)
	cases := []struct {
		name, description string
		focus             string
		nodeCap, edgeCap  int
		wantEdge, trunc   bool
	}{
		{"positive_focus_survives_caps", "the focus file's function and its caller are emitted first", "z/target.go", 2, 1, true, true},
		{"negative_no_focus_loses_edge", "walk order fills the caps with noise", "", 2, 1, false, true},
		{"corner_no_caps_hit", "with room for everything, both orders keep the edge", "", 100, 100, true, false},
		{"adversarial_focus_traversal", "a traversal focus entry matches nothing", "../z/target.go", 2, 1, false, true},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			out := analyze(root, parseFocus(c.focus), c.nodeCap, c.edgeCap)
			if len(out.Nodes) > c.nodeCap || len(out.Edges) > c.edgeCap {
				t.Fatalf("%s: caps exceeded: %d nodes, %d edges", c.description, len(out.Nodes), len(out.Edges))
			}
			ids := map[string]int{}
			for _, n := range out.Nodes {
				ids[n.Name] = n.ID
			}
			caller, okC := ids["Caller"]
			target, okT := ids["Target"]
			got := false
			if okC && okT {
				for _, e := range out.Edges {
					if e.CallerID == caller && e.CalleeID == target {
						got = true
					}
				}
			}
			if got != c.wantEdge {
				t.Errorf("%s: Caller→Target present = %v, want %v (%+v)", c.description, got, c.wantEdge, out)
			}
			if out.Truncated != c.trunc {
				t.Errorf("%s: truncated = %v, want %v", c.description, out.Truncated, c.trunc)
			}
			for i, n := range out.Nodes {
				if n.ID != i {
					t.Errorf("%s: node %d has id %d (ids are emission positions)", c.description, i, n.ID)
				}
			}
		})
	}
}

// A focus fn that calls one name from many sites, where many fns share that
// name: each fn is ranked once (hop1 is deduped), and every node keeps a rank.
func TestPriorityAdversarialFanout(t *testing.T) {
	const sharers, sites = 300, 2000
	nodes := []node{{Name: "F", File: "f.go"}}
	calls := [][]string{make([]string, sites)}
	for i := range calls[0] {
		calls[0][i] = "M"
	}
	for i := 0; i < sharers; i++ {
		nodes = append(nodes, node{Name: "M", File: "m.go"})
		calls = append(calls, nil)
	}
	order, rank := priority(nodes, calls, map[string]bool{"f.go": true})
	if len(order) != len(nodes) {
		t.Fatalf("order has %d entries, want %d", len(order), len(nodes))
	}
	if rank[0] != rankFocus {
		t.Errorf("F rank = %d, want focus", rank[0])
	}
	for i := 1; i < len(nodes); i++ {
		if rank[i] != rankHop1 {
			t.Fatalf("M #%d rank = %d, want hop1", i, rank[i])
		}
	}
}

// Many callers of a name many fns share: the edge scan stops at its work budget
// (marked truncated) instead of examining every pair, and still emits the focus
// fn's edges first.
func TestResolveEdgesWorkBudget(t *testing.T) {
	const fns = 2100 // 2100 callers × 2100 sharers > maxEdgeWork
	nodes := make([]node, fns)
	calls := make([][]string, fns)
	order := make([]int, fns)
	rank := make([]int, fns)
	newID := map[int]int{}
	for i := range nodes {
		nodes[i] = node{Name: "M"}
		calls[i] = []string{"M", "M", "M"} // repeated sites cost once
		order[i] = i
		rank[i] = rankRest
		newID[i] = i
	}
	rank[0] = rankFocus
	truncated := false
	edges := resolveEdges(order, calls, nodes, newID, rank, maxEdges, &truncated)
	if !truncated {
		t.Errorf("the scan should stop at its budget and say so")
	}
	if len(edges) == 0 || edges[0].CallerID != 0 {
		t.Errorf("the focus fn's edges should come first, got %d edges", len(edges))
	}
}
